#!/usr/bin/env python3
"""Generate fmodex.def for the proxy DLL.

Every export of the real fmodex.dll is forwarded to fmodex_real.<name>, except
the names listed in src/hooks.txt, which map to our hk_<Class>_<method>
functions. Also emits src/hooks_gen.h with the mangled names, so the C side
can resolve the real functions with GetProcAddress without retyping them.

usage: gen_def.py <exports.txt> <hooks.txt> <out.def> <out_hooks_gen.h>
"""
import re
import sys

MANGLED = re.compile(r"^\?([A-Za-z0-9_]+)@([A-Za-z0-9_]+)@FMOD@@")


def c_symbol(mangled):
    m = MANGLED.match(mangled)
    if not m:
        raise SystemExit(f"hook name is not a FMOD member function: {mangled}")
    method, cls = m.groups()
    return f"{cls}_{method}"


def main():
    exports_path, hooks_path, def_path, hdr_path = sys.argv[1:5]
    exports = [l.strip() for l in open(exports_path) if l.strip()]
    hooks = [l.strip() for l in open(hooks_path)
             if l.strip() and not l.lstrip().startswith("#")]

    if len(set(exports)) != len(exports):
        raise SystemExit("duplicate names in exports list")
    missing = [h for h in hooks if h not in exports]
    if missing:
        raise SystemExit("hooks not exported by fmodex.dll:\n  " + "\n  ".join(missing))
    syms = [c_symbol(h) for h in hooks]
    if len(set(syms)) != len(syms):
        raise SystemExit("two hooks map to the same C symbol (overload?)")

    hooked = dict(zip(hooks, syms))
    with open(def_path, "w", newline="\n") as f:
        f.write("; generated by tools/gen_def.py; do not edit\n")
        f.write("LIBRARY fmodex.dll\nEXPORTS\n")
        for name in exports:
            if name in hooked:
                f.write(f'"{name}"=hk_{hooked[name]}\n')
            else:
                f.write(f'"{name}"=fmodex_real."{name}"\n')

    with open(hdr_path, "w", newline="\n") as f:
        f.write("/* generated by tools/gen_def.py; do not edit */\n")
        f.write("/* X(CSymbol, \"mangled export name\") */\n")
        f.write("#define FMOD_HOOKS(X) \\\n")
        for name, sym in zip(hooks, syms):
            f.write(f'    X({sym}, "{name}") \\\n')
        f.write("\n")


if __name__ == "__main__":
    main()
